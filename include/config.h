#pragma once
#include <Arduino.h>

// =============================================================================
// 1. 脚ごとのハードウェア設定・初期調整
// =============================================================================
// 機体上から見て: FL=左前, FR=右前, RL=左後, RR=右後
struct LegConfig {
  const char* name;     // 脚の名前 (シリアル表示用)
  uint8_t chYaw;        // PCA9685 チャンネル番号: 付け根 (前後スイング)
  uint8_t chKnee;       // PCA9685 チャンネル番号: 膝 (上下リフト)
  int8_t  yawDir;       // 付け根の回転方向 (+1 または -1): 「前」に振るときの向き。逆なら符号を反転
  int8_t  kneeDir;      // 膝の回転方向 (+1 または -1): 「上」に上げるときの向き。逆なら符号を反転
  float   yawTrim;      // 付け根の角度微調整 [deg]: 90°で斜め45°を向かない場合のズレ補正 (例: +3.0f, -2.5f)
  float   kneeTrim;     // 膝の角度微調整 [deg]: 90°でスネが真下にならない場合のズレ補正
  float   offset;       // 歩行サイクル(0.0〜1.0)内で、その脚を上げ始めるタイミング (基本は変更しない)
};

// 遊脚順: FL(0.00) -> RR(0.25) -> FR(0.50) -> RL(0.75) の対角クロール歩容
// ※ `check` コマンドで1本ずつ動かしたとき、「上がる → 前に振る → 後ろに振る」になるよう yawDir/kneeDir を合わせる
const LegConfig LEGS[4] = {
  // name  chY chK  yDir kDir  yTrim  kTrim  offset
  { "FL",   0,  1,   +1,  +1,  0.0f,  0.0f,  0.00f },
  { "FR",   2,  3,   -1,  -1,  0.0f,  0.0f,  0.50f },
  { "RL",   4,  5,   +1,  +1,  0.0f,  0.0f,  0.25f },
  { "RR",   6,  7,   -1,  -1,  0.0f,  0.0f,  0.75f },
};

// =============================================================================
// 2. 歩容 (歩き方) パラメータ
// =============================================================================
// 実機寸法: 車体 150x150mm, 太もも(hip->knee) 60mm, スネ(knee->足先) 70mm

// 1周期にかける時間 [秒]
// 小さくすると速く歩くが、1.5秒未満はサーボの最高速度(0.13s/60°)に追いつかなくなるため注意
const float CYCLE_SEC   = 2.5f;

// 脚を前後に振る振幅 (片側) [deg]
// 大きくすると1歩の歩幅が伸びる (目安: 16°〜30°)
const float YAW_AMP     = 24.0f;

// 立ち姿勢でのスネの外開き角度 [deg] (0°=スネが真下、プラスで外へ開いて車体が低くなる)
// 0°だと膝を曲げても足がほとんど上がらないため、20°〜30°開いて立たせる
const float KNEE_STANCE = 25.0f;

// 遊脚時に立ち姿勢(KNEE_STANCE)からさらに膝を上げる角度 [deg]
// KNEE_STANCE=25°のとき: 28°で約21mm、48°で約43mm 足先が上がる (3cm段差には45°〜50°が必要)
const float KNEE_LIFT   = 48.0f;

// 1周期(1.0)のうち、1本の脚を空中へ上げている割合 (0.0〜0.25)
// 0.20 なら、各脚が 20% ずつ順番に浮き、残り 20% (各切り替え間の 5%×4回) は4脚すべてが接地する
const float SWING_DUTY  = 0.20f;

// =============================================================================
// 3. 制御周期・サーボ・通信設定
// =============================================================================
const uint16_t LOOP_DT_MS      = 20;      // 制御ループ周期 [ms] (20ms = 50Hz)

const int      SERVO_MIN_PULSE = 120;     // 0° に対応するPCA9685パルス幅 (4096段階中)
const int      SERVO_MAX_PULSE = 520;     // 180° に対応するPCA9685パルス幅 (4096段階中)
const float    NEUTRAL         = 90.0f;   // サーボの中立角度 [deg] (スネ真下・脚45°方向)

const long     BAUD_RATE       = 115200L; // シリアル通信速度 [bps]
